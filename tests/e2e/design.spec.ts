  await page.getByRole('button', { name: '에디토리얼 템플릿' }).click();
  await expect(page.getByLabel('첫 화면 큰 제목')).toHaveValue('주영과 현범,\n우리의 약속');
  await page.getByRole('button', { name: '실행 취소', exact: true }).click();
